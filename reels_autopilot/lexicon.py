def load_terms(domain: str, user_file: Path | None = None) -> list[str]:
    terms = list(GENERAL)
    if domain == "realestate":
        terms = REALESTATE + terms
    if user_file and user_file.exists():
        for line in user_file.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line and not line.startswith("#"):
                terms.insert(0, line)
    # 긴 말부터 맞춰야 '일반주거지역'이 '주거지역'보다 먼저 잡힘
    seen: set[str] = set()
    uniq = [t for t in terms if not (t in seen or seen.add(t))]
    return sorted(uniq, key=len, reverse=True)
